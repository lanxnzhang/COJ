@pytest.mark.parametrize("ending", [b"\r\n", b"\r", b"mixed"])
def test_line_ending_only_xml_retained_and_recorded(repositories, ending):
    root, source = repositories
    initial = importer.preview(root, source)
    for item in initial["writes"]:
        path = root / item["target"]
        path.parent.mkdir(parents=True, exist_ok=True)
        content = (root / item["payload"]).read_bytes()
        if path.suffix == ".xml":
            if ending == b"mixed":
                content = content.replace(b"\n", b"\r\n", 1)
            else:
                content = content.replace(b"\n", ending)
        path.write_bytes(content)
    commit(root)  # Simulate existing committed data, without an import manifest.
    before = {path: (path.read_bytes(), path.stat().st_mtime_ns) for path in (root / "data/xml").rglob("*.xml")}
    plan = importer.preview(root, source)
    assert not plan["blockers"]
    assert not plan["writes"]
    assert all(record["xml_line_endings_only"] for record in plan["files"].values())
    for relative, record in plan["files"].items():
        content = (root / record["xml_path"]).read_bytes()
        generated, _, _ = importer.convert(relative, (root / relative).read_bytes(), record["kind"])
        assert content != generated
        assert importer.normalize_line_endings(content) == importer.normalize_line_endings(generated)
        assert record["xml_sha256"] == importer.digest(content)
        assert record["generated_xml_sha256"] == importer.digest(generated)
        assert record["xml_normalized_sha256"] == importer.digest(importer.normalize_line_endings(content))
    assert importer.apply(root) == {"replaced": 0, "manifest_updated": True}
    assert all((path.read_bytes(), path.stat().st_mtime_ns) == original for path, original in before.items())
    commit(root)
    followup = importer.preview(root, source)
    assert not followup["blockers"]
    assert not followup["writes"]
    assert importer.apply(root) == {"replaced": 0, "manifest_updated": False}


