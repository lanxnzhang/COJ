TEXT = '=N(" nu ")\nIP-MAT,N,L000006a,LOG,nu\nID,BS.1\n'
DICT = '---------------------------------------------------\n=== L000006a\n.FORM\tnu\n.GLOSS\tNEG\n'


def command(repo, *args):
    return subprocess.run(["git", "-c", f"safe.directory={repo.as_posix()}", "-C", str(repo), *args],
                          capture_output=True, check=True).stdout


def commit(repo):
    command(repo, "add", ".")
    command(repo, "-c", "user.name=Importer Test", "-c", "user.email=test@example.invalid",
            "commit", "--allow-empty", "-m", "fixture")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


