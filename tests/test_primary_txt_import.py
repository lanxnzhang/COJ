def test_normalization_failure_rolls_back_import_and_formatting(repositories, monkeypatch):
    root, source = repositories
    legacy_xml_fixture(root, source)
    write(source / "oncoj_source/trees/BS.txt", TEXT.replace(",nu", ",no"))
    commit(source / "oncoj_source")
    plan = importer.preview(root, source, normalize_xml=True)
    before = {path: path.read_bytes() for path in (root / "data").rglob("*") if path.is_file()}
    target = root / plan["normalization"]["writes"][1]["target"]
    replace = importer.os.replace
    failed = False
    def failing(src, dst):
        nonlocal failed
        if Path(dst) == target and not failed:
            failed = True
            raise OSError("normalization failure")
        return replace(src, dst)
    monkeypatch.setattr(importer.os, "replace", failing)
    with pytest.raises(OSError, match="normalization failure"):
        importer.apply(root)
    assert {path: path.read_bytes() for path in (root / "data").rglob("*") if path.is_file()} == before


