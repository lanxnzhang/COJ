def legacy_xml_fixture(root, source):
    initial = importer.preview(root, source)
    for item in initial["writes"]:
        path = root / item["target"]
        path.parent.mkdir(parents=True, exist_ok=True)
        content = (root / item["payload"]).read_bytes()
        if path.suffix == ".xml":
            tree = ET.fromstring(content)
            for node in tree.iter():
                attributes = list(reversed(list(node.attrib.items())))
                node.attrib.clear()
                node.attrib.update(attributes)
            ET.indent(tree, space="    ")
            content = ET.tostring(tree, encoding="utf-8", xml_declaration=True, short_empty_elements=False).replace(b"\n", b"\r\n")
        path.write_bytes(content)
    write(root / "scripteditor/runs/history/data.xml", '<history z="2" a="1"/>')
    write(root / "compreditor/workspace/copy.xml", '<copy z="2" a="1"/>')
    commit(root)
    return initial


def test_ordered_import_then_normalization_and_final_manifest(repositories, monkeypatch):
    root, source = repositories
    legacy_xml_fixture(root, source)
    write(source / "oncoj_source/trees/BS.txt", TEXT.replace(",nu", ",no"))
    commit(source / "oncoj_source")
    before = {path: path.read_bytes() for path in root.rglob("*.xml")}
    plan = importer.preview(root, source, normalize_xml=True)
    assert not plan["blockers"]
    assert {item["target"] for item in plan["writes"]} == {"data/txt/trees/BS.txt", "data/xml/trees/BS.xml"}
    norm = plan["normalization"]
    assert len(norm["files"]) == norm["semantics_verified"] == 4
    assert len(norm["writes"]) == 3
    assert all(path.read_bytes() == content for path, content in before.items())
    replaced = []
    replace = importer.os.replace
    def tracked(src, dst):
        if Path(dst).is_relative_to(root / "data"):
            replaced.append(Path(dst).relative_to(root).as_posix())
        return replace(src, dst)
    monkeypatch.setattr(importer.os, "replace", tracked)
    assert importer.apply(root)["replaced"] == 5
    assert replaced[:2] == [item["target"] for item in plan["writes"]]
    assert replaced[2:-1] == [item["target"] for item in norm["writes"]]
    manifest = json.loads((root / importer.MANIFEST).read_text())
    for path in (root / "data/xml").rglob("*.xml"):
        assert path.read_bytes() == importer.canonical_xml(path.read_bytes())
    for record in manifest["files"].values():
        assert record["xml_sha256"] == importer.digest((root / record["xml_path"]).read_bytes())
    assert (root / "scripteditor/runs/history/data.xml").read_bytes() == before[root / "scripteditor/runs/history/data.xml"]
    assert (root / "compreditor/workspace/copy.xml").read_bytes() == before[root / "compreditor/workspace/copy.xml"]
    commit(root)
    followup = importer.preview(root, source, normalize_xml=True)
    assert not followup["writes"] and not followup["normalization"]["writes"]
    assert importer.apply(root) == {"replaced": 0, "manifest_updated": False}


