def establish(root, source):
    plan = importer.preview(root, source)
    assert not plan["blockers"]
    result = importer.apply(root)
    assert result["replaced"] == 8
    commit(root)
    return plan


def test_preview_only_and_committed_source(repositories):
    root, source = repositories
    write(source / "oncoj_source/trees/BS.txt", "uncommitted broken text")
    plan = importer.preview(root, source)
    assert not plan["blockers"]
    assert not (root / "data").exists()
    assert len(plan["files"]) == 4
    staged = next(item for item in plan["writes"] if item["target"] == "data/txt/trees/BS.txt")
    assert (root / staged["payload"]).read_text(encoding="utf-8") == TEXT
    assert (source / "oncoj_source/trees/BS.txt").read_text() == "uncommitted broken text"


def test_incremental_conversion_and_noop(repositories, monkeypatch):
    root, source = repositories
    establish(root, source)
    calls = []
    original = importer.convert
    def tracked(*args):
        calls.append(args[0])
        return original(*args)
    monkeypatch.setattr(importer, "convert", tracked)
    plan = importer.preview(root, source)
    assert plan["writes"] == []
    assert calls == []
    assert importer.apply(root) == {"replaced": 0, "manifest_updated": False}
    write(source / "oncoj_source/trees/BS.txt", TEXT.replace(",nu", ",no"))
    commit(source / "oncoj_source")
    untouched = root / "data/xml/trees/FK.xml"
    before = untouched.stat().st_mtime_ns
    plan = importer.preview(root, source)
    assert calls == ["data/txt/trees/BS.txt"]
    assert {item["target"] for item in plan["writes"]} == {"data/txt/trees/BS.txt", "data/xml/trees/BS.xml"}
    importer.apply(root)
    assert untouched.stat().st_mtime_ns == before
    assert (root / "data/txt/trees/BS.txt").read_text() == TEXT.replace(",nu", ",no")
    assert "no" in (root / "data/xml/trees/BS.xml").read_text()


