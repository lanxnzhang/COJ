@pytest.mark.parametrize("existing", [False, True])
def test_partial_apply_rolls_back(repositories, monkeypatch, existing):
    root, source = repositories
    if existing:
        establish(root, source)
        write(source / "oncoj_source/trees/BS.txt", TEXT.replace(",nu", ",no"))
        commit(source / "oncoj_source")
    before = {path.relative_to(root): path.read_bytes() for path in (root / "data").rglob("*") if path.is_file()}
    importer.preview(root, source)
    replace = importer.os.replace
    attempts = 0
    def failing_replace(src, dst):
        nonlocal attempts
        if Path(dst).suffix in (".txt", ".xml"):
            attempts += 1
            if attempts == 2:
                raise OSError("simulated write failure")
        return replace(src, dst)
    monkeypatch.setattr(importer.os, "replace", failing_replace)
    with pytest.raises(OSError, match="simulated"):
        importer.apply(root)
    after = {path.relative_to(root): path.read_bytes() for path in (root / "data").rglob("*") if path.is_file()}
    assert after == before
    journal = json.loads((root / importer.CACHE / "transaction.json").read_text())
    assert journal["status"] == "rolled_back"


