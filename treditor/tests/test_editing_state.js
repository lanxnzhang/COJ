"use strict";
const assert = require("node:assert/strict");
const {State, filenameForText} = require("../static/editing-state.js");
let next = 0;
const state = new State(() => `persistent-${++next}`);
const segment = state.addSegment();
const first = state.addComponent(segment, "taka");
const repeated = state.addComponent(segment, "taka");
assert.notEqual(first, repeated);
assert.strictEqual(state.terminals()[0].occurrence, state.document.occurrences[first]);
state.editOccurrence(first, "form", "corrected");
assert.equal(state.terminals()[0].occurrence.form, "corrected");
assert.equal(state.document.occurrences[repeated].form, "taka");
const node = state.terminals()[0].syntax;
assert.equal(node.node.occurrence, first);
assert.equal(node.node.form, undefined);
state.editOccurrence(first, "lemma", "L007005");
state.saved("KK.67.syn.json", "revision-a");
assert.equal(state.expectedRevision(), "revision-a");
const saved = JSON.parse(JSON.stringify(state.document));
state.reset(); state.open(saved, "KK.67.syn.json", "revision-a");
assert.deepEqual(state.document, saved);
assert.equal(state.dirty, false);
assert.strictEqual(state.terminals()[0].occurrence, state.document.occurrences[first]);
assert.equal(state.terminals()[0].syntax.id, node.id);
state.filename = "copy.syn.json";
assert.equal(state.expectedRevision(), null);
state.document.syntax_nodes = {}; state.document.syntax_roots = [];
assert.equal(state.terminals().length, 2);
assert.equal(state.terminals()[0].syntax, null);
console.log("Editing state identity/reopen/shared-reference checks passed.");
assert.equal(filenameForText(" KK.67 "), "KK.67.syn.json");
for (const id of ["", "../escape", "NUL", "CON.txt", "A/B", "A B"]) assert.throws(() => filenameForText(id));
const removalState = new State(() => `remove-${++next}`);
const s = removalState.addSegment(), a = removalState.addComponent(s, "taka"), b = removalState.addComponent(s, "taka");
const beforeRemoval = JSON.stringify(removalState.document);
removalState.removeComponent(s, a);
assert.equal(removalState.document.occurrences[a], undefined);
assert.equal(removalState.terminals().length, 1);
assert.equal(removalState.terminals()[0].id, b);
removalState.undoRemoval();
assert.equal(JSON.stringify(removalState.document), beforeRemoval);
removalState.removeSegment(s);
assert.equal(removalState.document.segment_order.length, 0);
assert.equal(Object.keys(removalState.document.occurrences).length, 0);
assert.equal(Object.keys(removalState.document.syntax_nodes).length, 0);
removalState.undoRemoval();
assert.equal(JSON.stringify(removalState.document), beforeRemoval);
const otherSegment = removalState.addSegment();
removalState.document.segments[otherSegment].occurrences.push(a);
removalState.removeComponent(s, a);
assert.equal(removalState.document.occurrences[a].form, "taka");
removalState.undoRemoval();
removalState.document.composition_groups.g = {children: [{kind: "occurrence", id: b}]};
const protectedDocument = JSON.stringify(removalState.document);
assert.throws(() => removalState.removeSegment(s), /lexical analysis/);
assert.equal(JSON.stringify(removalState.document), protectedDocument);
console.log("Text-ID filenames, removal/undo and protected-analysis checks passed.");
