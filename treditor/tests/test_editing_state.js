"use strict";
const assert = require("node:assert/strict");
const {State} = require("../static/editing-state.js");
let next = 0;
const state = new State(() => `persistent-${++next}`);
const segment = state.addSegment();
const first = state.addComponent(segment, "taka");
const repeated = state.addComponent(segment, "taka");
assert.notEqual(first, repeated);
assert.strictEqual(state.terminals()[0].occurrence, state.document.occurrences[first]);
state.editOccurrence(first, "form", "corrected");
assert.equal(state.terminals()[0].occurrence.form, "corrected");
assert.equal(state.document.occurrences[repeated].form, "taka");
const node = state.terminals()[0].syntax;
assert.equal(node.node.occurrence, first);
assert.equal(node.node.form, undefined);
state.editOccurrence(first, "lemma", "L007005");
state.saved("KK.67.syn.json", "revision-a");
assert.equal(state.expectedRevision(), "revision-a");
const saved = JSON.parse(JSON.stringify(state.document));
state.reset(); state.open(saved, "KK.67.syn.json", "revision-a");
assert.deepEqual(state.document, saved);
assert.equal(state.dirty, false);
assert.strictEqual(state.terminals()[0].occurrence, state.document.occurrences[first]);
assert.equal(state.terminals()[0].syntax.id, node.id);
state.filename = "copy.syn.json";
assert.equal(state.expectedRevision(), null);
state.document.syntax_nodes = {}; state.document.syntax_roots = [];
assert.equal(state.terminals().length, 2);
assert.equal(state.terminals()[0].syntax, null);
console.log("Editing state identity/reopen/shared-reference checks passed.");
