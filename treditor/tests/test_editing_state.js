"use strict";
const assert = require("node:assert/strict");
const {State, filenameForDocument, parsePairs, units} = require("../static/editing-state.js");
let id = 0;
const state = new State(() => `id-${++id}`);
const first = state.addText("KK.67");
const passage = state.addPassage("多迦由久夜", "taka yuku ya");
assert.deepEqual(state.text.passages[passage].units, [{start: 0, end: 4}, {start: 5, end: 9}, {start: 10, end: 12}]);
assert.deepEqual(state.text.nodes, {});
state.addText("KK.68"); state.addPassage("原文", "another text");
state.selectText(first);
assert.equal(state.text.passages[passage].transcription, "taka yuku ya");
const node = {category: "VB", lemma: "L1", form: "takayukuya", children: [], parts: [], script: null, annotations: {}};
state.text.nodes.n = node; state.text.roots = ["n"];
state.text.links.l = {node: "n", passage, part: null, start: 0, end: 10, status: "valid", reason: "",
  evidence: {original: "多迦由久夜", transcription: "taka yuku ya", status: "valid", reason: ""}};
const evidence = JSON.stringify(state.text.links.l.evidence);
state.editPassage(passage, "transcription", "taka  yukuya");
assert.equal(state.text.links.l.status, "valid");
state.editPassage(passage, "transcription", "changed");
assert.equal(state.text.links.l.status, "unresolved");
assert.equal(JSON.stringify(state.text.links.l.evidence), evidence);
assert.strictEqual(state.text.nodes.n, node);
state.removePassage(passage);
assert.equal(state.text.links.l.status, "unresolved");
assert.ok(state.unresolved()[0].includes("Removed passage"));
state.undoRemoval();
assert.equal(state.text.passages[passage].transcription, "changed");
const saved = JSON.parse(JSON.stringify(state.document));
state.open(saved, "KK.syn.json", "revision");
assert.equal(state.dirty, false); assert.equal(state.expectedRevision(), "revision");
assert.deepEqual(state.document, saved);
assert.equal(filenameForDocument("KK"), "KK.syn.json");
assert.throws(() => filenameForDocument("../escape"));
assert.throws(() => filenameForDocument("CON"));
assert.deepEqual(units("𠮷 a"), [{start: 0, end: 1}, {start: 2, end: 3}]);
assert.deepEqual(parsePairs("1 多迦由久夜\n taka yuku ya\n\n2 波夜夫佐和気能\n payabusawake no"),
  [{original: "多迦由久夜", transcription: "taka yuku ya"}, {original: "波夜夫佐和気能", transcription: "payabusawake no"}]);
for (const bad of ["1 original", "2 original\ntranscription", "1 original\ntranscription\noriginal\ntranscription"]) assert.throws(() => parsePairs(bad));
console.log("Document state, input boundaries, identities, permissive reconciliation, orphan preservation and bulk pairing passed.");

// Insertion shifts display positions, never existing identities or link evidence.
state.selectText(first);
const before = state.text.passage_order.slice(), oldNodes = JSON.stringify(state.text.nodes), oldLinks = JSON.stringify(state.text.links);
const middle = state.addPassage("middle", "mid dle", 0);
assert.deepEqual(state.text.passage_order, [middle, ...before]);
assert.equal(JSON.stringify(state.text.nodes), oldNodes); assert.equal(JSON.stringify(state.text.links), oldLinks);
assert.throws(() => state.addPassage("", "", -1));
assert.throws(() => state.addPassage("", "", 99));
state.removePassage(middle); assert.deepEqual(state.text.passage_order, before);
state.undoRemoval(); assert.equal(state.text.passage_order[0], middle);
